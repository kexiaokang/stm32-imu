/*
 * W9-2：从 128 个原始采样点算出 19 维特征
 * =====================================================================
 *
 * 为什么需要这一步（一句话）：
 *   传感器给的是"某一瞬间的 6 个读数"，一秒内变 100 次。
 *   分类器需要的是"这 1.28 秒整体是什么样"，也就是统计量。
 *   所以中间必须有一次压缩：768 个数字 -> 19 个数字。
 *
 * 为什么要 128 个点：
 *   100 Hz 采样，128 点 = 1.28 秒。一个动作在这个时长里刚好"做完一遍"
 *   （晃动 2~3 个来回、翻面翻完、旋转转好几圈）。
 *   太短：一个动作还没做完，看不出特征；
 *   太长：两个动作被切进同一个窗口，标签就不对了。
 *
 * 19 维的构成：
 *   6 个轴 × 3 个统计量 = 18
 *   + 1 个 az 负值比例 = 19
 *
 * 但注意：这 19 个数【不是】模型自己挑的，是训练前人为设计的。
 *   模型只负责在 19 个里挑"用哪几个、阈值多少"。
 *   特征设计得好不好，决定了模型的天花板。
 */
#ifndef FEATURES_H
#define FEATURES_H

#include <stdint.h>
#include "model_data.h"     /* 为了拿到 N_FEATURES = 19 */

#define WIN_LEN  128        /* 一个窗口 128 个时间点 = 1.28 秒 */
#define N_AXES     6        /* ax ay az gx gy gz */

/*
 * 输入：win[i][a] = 第 i 个时间点、第 a 个轴的原始读数
 *       a = 0..2 是加速度 x/y/z，3..5 是角速度 x/y/z
 * 输出：f[0..18]，顺序见 features.c 里的 FEATURE_NAMES_C
 */
void extract_features(const int16_t win[WIN_LEN][N_AXES], float f[N_FEATURES]);

/* 19 维特征的名字，报错时用来定位 */
extern const char *FEATURE_NAMES_C[N_FEATURES];

#endif  /* FEATURES_H */
